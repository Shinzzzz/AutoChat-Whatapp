import PDFDocument from "pdfkit";
import { paiseToInr, type Totals } from "./invoice.js";

export interface DocumentData {
  kind: "Quotation" | "Tax Invoice";
  number: string;
  date: Date;
  brandName: string;
  brandAddress?: string;
  customerName: string;
  customerContact?: string;
  lineLabel: string; // e.g. "1,000 × 500ml glass (vanity)"
  quantity: number;
  unitPricePaise: number;
  totals: Totals;
  note?: string;
}

/** Render a quotation / invoice PDF to a Buffer. */
export function renderDocumentPdf(data: DocumentData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50 });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    // Header
    doc.fontSize(20).text(data.brandName, { continued: false });
    if (data.brandAddress) doc.fontSize(9).fillColor("#666").text(data.brandAddress);
    doc.moveDown(0.5);
    doc.fillColor("#000").fontSize(16).text(data.kind, { align: "right" });
    doc
      .fontSize(10)
      .fillColor("#444")
      .text(`No: ${data.number}`, { align: "right" })
      .text(`Date: ${data.date.toISOString().slice(0, 10)}`, { align: "right" });
    doc.moveDown(1);

    // Bill to
    doc.fillColor("#000").fontSize(11).text("Bill To:");
    doc.fontSize(10).fillColor("#444").text(data.customerName);
    if (data.customerContact) doc.text(data.customerContact);
    doc.moveDown(1);

    // Line items table
    doc.fillColor("#000").fontSize(10);
    const y = doc.y;
    doc.text("Description", 50, y);
    doc.text("Qty", 320, y);
    doc.text("Unit", 380, y);
    doc.text("Amount", 460, y, { align: "right" });
    doc.moveTo(50, doc.y + 2).lineTo(545, doc.y + 2).strokeColor("#ccc").stroke();
    doc.moveDown(0.5);
    const ry = doc.y;
    doc.fillColor("#444");
    doc.text(data.lineLabel, 50, ry, { width: 260 });
    doc.text(String(data.quantity), 320, ry);
    doc.text(paiseToInr(data.unitPricePaise), 380, ry);
    doc.text(paiseToInr(data.totals.subtotalPaise), 460, ry, { align: "right" });
    doc.moveDown(2);

    // Totals
    const tx = 380;
    doc.fillColor("#000");
    doc.text("Subtotal", tx, doc.y);
    doc.text(paiseToInr(data.totals.subtotalPaise), 460, doc.y, { align: "right" });
    doc.text(`GST (${data.totals.gstPercent}%)`, tx, doc.y + 2);
    doc.text(paiseToInr(data.totals.taxPaise), 460, doc.y, { align: "right" });
    doc.moveDown(0.3);
    doc.fontSize(12).text("Total", tx, doc.y);
    doc.text(paiseToInr(data.totals.totalPaise), 460, doc.y, { align: "right" });

    if (data.note) {
      doc.moveDown(2).fontSize(9).fillColor("#666").text(data.note, 50);
    }
    doc.moveDown(2).fontSize(8).fillColor("#999").text(
      `${data.kind} generated by ${data.brandName}.`,
      50,
      undefined,
      { align: "center" },
    );

    doc.end();
  });
}
